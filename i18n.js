function t(key, vars = {}) {
  const lang = (window.state && window.state.language) || 'ar';
  let text = (I18N[lang] || I18N.ar)[key] || key;
  Object.entries(vars).forEach(([k, v]) => { text = text.replace(`{${k}}`, v); });
  return text;
}

// Spoken-text helper: same as t() but numbers are spelled out (e.g. 3 → "ثلاثة")
// so the TTS engine pronounces them naturally instead of "three" or hesitating.
function tSpoken(key, vars = {}) {
  const lang = (window.state && window.state.language) || 'ar';
  let text = (I18N[lang] || I18N.ar)[key] || key;
  Object.entries(vars).forEach(([k, v]) => {
    let val = v;
    if (typeof v === 'number' && typeof Voice !== 'undefined') {
      val = lang === 'ar'
        ? (Voice._arNumbers[v] || String(v))
        : Voice._enNumber(v);
    }
    text = text.replace(`{${k}}`, val);
  });
  return text;
}

