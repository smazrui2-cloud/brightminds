function speakI18n(key, vars = {}) {
  if (typeof Voice === 'undefined') return;
  const lang = (window.state && window.state.language) || 'ar';

  // 1️⃣ Prefer pre-recorded natural-voice clip when available
  if (typeof CloudVoice !== 'undefined' && CloudVoice.enabled) {
    const clipKey = CLOUD_KEY_MAP[key];
    if (clipKey && CloudVoice.has(clipKey, lang)) {
      CloudVoice.play(clipKey, lang);
      return;
    }
  }

  // 2️⃣ Fall back to Web Speech API (works for any dynamic text)
  Voice.speak(tSpoken(key, vars), lang);
}

function applyI18n() {
  const lang = (window.state && window.state.language) || 'ar';
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.querySelectorAll('[data-t]').forEach(el => {
    el.textContent = t(el.dataset.t);
  });
  document.querySelectorAll('[data-soon-t]').forEach(el => {
    el.setAttribute('data-soon', t(el.dataset.soonT));
  });
}
